import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const common = {
  absWorkingDir: root,
  bundle: true,
  write: false,
  platform: 'browser',
  format: 'iife',
  target: ['chrome120'],
  conditions: ['browser'],
  loader: { '.wasm': 'binary' },
  // Emscripten uses this only to resolve external resources; our variant supplies
  // embedded bytes and explicitly rejects fallback loads.
  define: { 'import.meta.url': '"chudpresence-embedded-v2-engine"' },
  minify: true,
  legalComments: 'none',
};
for (const [name, globalName] of [['engine', 'ChudPresenceV2Engine'], ['page', 'ChudPresenceV2Page']]) {
  const result = await build({
    ...common,
    entryPoints: [`extension/core/activity-v2-${name}.js`],
    globalName,
    banner: { js: '// Generated by scripts/build-v2-engine.mjs. Do not edit.' +
      (name === 'engine' ? '\n// QuickJS / quickjs-emscripten: see ../vendor/QUICKJS-NOTICE.txt.' : '') },
    footer: { js: `globalThis.${globalName} = ${globalName};` },
  });
  assert.equal(result.outputFiles.length, 1);
  const output = result.outputFiles[0].text;
  const destination = path.join(root, 'extension', 'core', `activity-v2-${name}.generated.js`);
  if (process.argv.includes('--check')) {
    assert.ok(await fs.readFile(destination, 'utf8') === output, `Activity v2 ${name} bundle is stale. Run npm run build:v2-engine.`);
    console.log(`Activity v2 ${name} bundle is current.`);
  } else {
    await fs.writeFile(destination, output);
    console.log(`Built extension/core/activity-v2-${name}.generated.js.`);
  }
}
